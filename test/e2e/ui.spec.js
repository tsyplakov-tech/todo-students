import { test, expect } from '@playwright/test';
const token = 'e2e-token-only-for-local-ci-tests-123456';
test('browser login, create, rename, complete, run filter, delete, manual task, logout', async ({ page, request }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.getByLabel('Bearer-токен').fill('wrong'); await page.getByRole('button',{ name:'Войти',exact:true }).click();
  await expect(page.getByRole('status')).toContainText('Требуется');
  await page.getByLabel('Bearer-токен').fill(token); await page.getByRole('button',{ name:'Войти',exact:true }).click();
  await expect(page.locator('#author-name')).toHaveText('Тестовый Студент');
  await expect(page.locator('#author-login')).toContainText('e2e_student');
  const runId = `ui_${Date.now()}`;
  await page.getByLabel('Группа дел (runId)').fill(runId); await page.getByRole('button',{ name:'Обновить',exact:true }).click();
  await expect(page.locator('#empty')).toBeVisible();
  const title = '<img src=x onerror=alert(1)> Учёба';
  await page.getByLabel('Новое дело',{ exact:true }).fill(title); await page.getByRole('button',{ name:'Добавить',exact:true }).click();
  await expect(page.locator('.task-title')).toHaveText(title); await expect(page.locator('.task img')).toHaveCount(0);
  await page.getByRole('button',{ name:'Изменить',exact:true }).click();
  await page.getByLabel('Новое название').fill('Готово к проверке'); await page.getByRole('button',{ name:'Сохранить' }).click();
  await expect(page.locator('.task-title')).toHaveText('Готово к проверке');
  await page.getByRole('checkbox').check(); await expect(page.locator('.task')).toHaveClass('task done');
  await page.getByLabel('Группа дел (runId)').fill(`${runId}_empty`); await page.getByRole('button',{ name:'Обновить',exact:true }).click();
  await expect(page.locator('.task')).toHaveCount(0);
  await page.getByLabel('Группа дел (runId)').fill(runId); await page.getByRole('button',{ name:'Обновить',exact:true }).click();
  await expect(page.locator('.task-title')).toHaveText('Готово к проверке');
  await page.getByRole('button',{ name:'Удалить',exact:true }).click(); await expect(page.locator('#empty')).toBeVisible();
  await page.getByRole('button',{ name:'Добавить итоговую работу' }).click();
  await expect(page.locator('.task-title')).toHaveText('Итоговая работа 24.10.2026: e2e_student');
  const manual = await request.get('/api/tasks/?runId=manual',{ headers:{ Authorization:`Bearer ${token}` } });
  const tasks = await manual.json();
  for (const task of tasks) await request.delete(`/api/tasks/${task.id}/`,{ headers:{ Authorization:`Bearer ${token}` } });
  await page.reload(); await expect(page.locator('#login-panel')).toBeVisible();
  expect(await page.evaluate(() => [localStorage.length,sessionStorage.length])).toEqual([0,0]);
  await page.getByLabel('Bearer-токен').fill(token); await page.getByRole('button',{ name:'Войти',exact:true }).click();
  await page.getByRole('button',{ name:'Выйти',exact:true }).click(); await expect(page.locator('#login-panel')).toBeVisible();
  expect(errors).toEqual([]);
});
